-- Entregas unicas por venda.
--
-- Principios de seguranca:
-- 1. Nenhum segredo e armazenado em texto puro. O backend grava somente
--    ciphertext AES-256-GCM, IV, auth tag e uma impressao HMAC.
-- 2. As tabelas nao possuem policies para anon/authenticated. Todo acesso passa
--    pelas rotas server-side, que usam service_role e validam propriedade.
-- 3. A alocacao ocorre no PostgreSQL, na mesma transacao que aprova o pedido,
--    usando FOR UPDATE SKIP LOCKED e restricoes UNIQUE.
-- 4. Uma entrega atribuida nunca volta ao estoque, inclusive apos estorno.

ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS buyer_email_normalized TEXT;

UPDATE public.orders
SET buyer_email_normalized = LOWER(BTRIM(buyer_email))
WHERE buyer_email IS NOT NULL
  AND buyer_email_normalized IS DISTINCT FROM LOWER(BTRIM(buyer_email));

CREATE INDEX IF NOT EXISTS idx_orders_buyer_email_normalized_paid
    ON public.orders(buyer_email_normalized, created_at DESC)
    WHERE status = 'paid' AND buyer_email_normalized IS NOT NULL;

CREATE OR REPLACE FUNCTION public.goupay_normalize_order_buyer_email()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    NEW.buyer_email_normalized := NULLIF(LOWER(BTRIM(NEW.buyer_email)), '');
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS normalize_order_buyer_email ON public.orders;
CREATE TRIGGER normalize_order_buyer_email
BEFORE INSERT OR UPDATE OF buyer_email ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.goupay_normalize_order_buyer_email();

CREATE TABLE IF NOT EXISTS public.unique_delivery_settings (
    product_id UUID PRIMARY KEY REFERENCES public.products(id) ON DELETE CASCADE,
    seller_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    enabled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_delivery_settings_enabled_at_check
        CHECK (NOT enabled OR enabled_at IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_unique_delivery_settings_seller
    ON public.unique_delivery_settings(seller_id);

CREATE TABLE IF NOT EXISTS public.unique_delivery_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    inventory_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id UUID NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    seller_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    payload_ciphertext TEXT NOT NULL,
    payload_iv TEXT NOT NULL,
    payload_auth_tag TEXT NOT NULL,
    payload_fingerprint CHAR(64) NOT NULL,
    encryption_version SMALLINT NOT NULL DEFAULT 1 CHECK (encryption_version >= 1),
    status TEXT NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'assigned', 'disabled')),
    assigned_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_delivery_item_assignment_state_check CHECK (
        (status = 'assigned' AND assigned_at IS NOT NULL)
        OR (status <> 'assigned')
    ),
    CONSTRAINT unique_delivery_item_fingerprint_unique
        UNIQUE (product_id, payload_fingerprint)
);

CREATE INDEX IF NOT EXISTS idx_unique_delivery_items_available
    ON public.unique_delivery_items(product_id, created_at, id)
    WHERE status = 'available';

CREATE INDEX IF NOT EXISTS idx_unique_delivery_items_seller
    ON public.unique_delivery_items(seller_id, product_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.unique_delivery_files (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    item_id UUID NOT NULL REFERENCES public.unique_delivery_items(id) ON DELETE CASCADE,
    product_id UUID NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    seller_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    storage_path TEXT NOT NULL UNIQUE,
    metadata_ciphertext TEXT NOT NULL,
    metadata_iv TEXT NOT NULL,
    metadata_auth_tag TEXT NOT NULL,
    file_iv TEXT NOT NULL,
    file_auth_tag TEXT NOT NULL,
    encryption_version SMALLINT NOT NULL DEFAULT 1 CHECK (encryption_version >= 1),
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0 AND size_bytes <= 15728640),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_unique_delivery_files_item
    ON public.unique_delivery_files(item_id, created_at);

CREATE TABLE IF NOT EXISTS public.unique_delivery_fulfillments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id UUID NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    seller_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    item_id UUID REFERENCES public.unique_delivery_items(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'stock_unavailable'
        CHECK (status IN ('assigned', 'stock_unavailable')),
    assigned_at TIMESTAMPTZ,
    first_viewed_at TIMESTAMPTZ,
    last_viewed_at TIMESTAMPTZ,
    view_count INTEGER NOT NULL DEFAULT 0 CHECK (view_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_delivery_fulfillment_order_product_unique
        UNIQUE (order_id, product_id),
    CONSTRAINT unique_delivery_fulfillment_item_unique
        UNIQUE (item_id),
    CONSTRAINT unique_delivery_fulfillment_state_check CHECK (
        (status = 'assigned' AND item_id IS NOT NULL AND assigned_at IS NOT NULL)
        OR (status = 'stock_unavailable' AND item_id IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_unique_delivery_fulfillments_seller
    ON public.unique_delivery_fulfillments(seller_id, product_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_unique_delivery_fulfillments_waiting
    ON public.unique_delivery_fulfillments(product_id, created_at)
    WHERE status = 'stock_unavailable';

