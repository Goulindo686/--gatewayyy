CREATE OR REPLACE FUNCTION public.goupay_backfill_waiting_unique_delivery()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_order_id UUID;
BEGIN
    IF NEW.status <> 'available' THEN
        RETURN NEW;
    END IF;

    SELECT fulfillment.order_id
    INTO v_order_id
    FROM public.unique_delivery_fulfillments AS fulfillment
    JOIN public.orders AS payment_order
      ON payment_order.id = fulfillment.order_id
     AND payment_order.status = 'paid'
    WHERE fulfillment.product_id = NEW.product_id
      AND fulfillment.seller_id = NEW.seller_id
      AND fulfillment.status = 'stock_unavailable'
    ORDER BY payment_order.created_at, fulfillment.created_at
    FOR UPDATE OF fulfillment SKIP LOCKED
    LIMIT 1;

    IF v_order_id IS NOT NULL THEN
        PERFORM public.assign_unique_delivery_for_product(
            v_order_id,
            NEW.product_id
        );
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS backfill_waiting_unique_delivery
