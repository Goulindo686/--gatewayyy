CREATE OR REPLACE FUNCTION public.assign_unique_delivery_for_product(
    p_order_id UUID,
    p_product_id UUID
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_order public.orders%ROWTYPE;
    v_enabled_at TIMESTAMPTZ;
    v_fulfillment_id UUID;
    v_fulfillment_status TEXT;
    v_existing_item_id UUID;
    v_item_id UUID;
BEGIN
    SELECT *
    INTO v_order
    FROM public.orders
    WHERE id = p_order_id;

    IF NOT FOUND
       OR v_order.status <> 'paid'
       OR p_product_id IS NULL
       OR v_order.seller_id IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT settings.enabled_at
    INTO v_enabled_at
    FROM public.unique_delivery_settings AS settings
    JOIN public.products AS product
      ON product.id = settings.product_id
     AND product.user_id = settings.seller_id
    WHERE settings.product_id = p_product_id
      AND settings.seller_id = v_order.seller_id
      AND (
          settings.enabled = TRUE
          OR EXISTS (
              SELECT 1
              FROM public.unique_delivery_order_products AS purchased_product
              WHERE purchased_product.order_id = v_order.id
                AND purchased_product.product_id = p_product_id
                AND purchased_product.seller_id = v_order.seller_id
          )
      );

    IF NOT FOUND
       OR v_enabled_at IS NULL
       OR v_order.created_at < v_enabled_at THEN
        RETURN NULL;
    END IF;

    INSERT INTO public.unique_delivery_fulfillments (
        order_id,
        product_id,
        seller_id,
        status
    )
    VALUES (
        v_order.id,
        p_product_id,
        v_order.seller_id,
        'stock_unavailable'
    )
    ON CONFLICT (order_id, product_id) DO NOTHING;

    SELECT id, status, item_id
    INTO v_fulfillment_id, v_fulfillment_status, v_existing_item_id
    FROM public.unique_delivery_fulfillments
    WHERE order_id = v_order.id
      AND product_id = p_product_id
    FOR UPDATE;

    IF v_fulfillment_status = 'assigned' THEN
        RETURN v_existing_item_id;
    END IF;

    SELECT item.id
    INTO v_item_id
    FROM public.unique_delivery_items AS item
    WHERE item.product_id = p_product_id
      AND item.seller_id = v_order.seller_id
      AND item.status = 'available'
    ORDER BY item.created_at, item.id
    FOR UPDATE SKIP LOCKED
    LIMIT 1;

    IF v_item_id IS NULL THEN
        RETURN NULL;
    END IF;

    UPDATE public.unique_delivery_items
    SET status = 'assigned',
        assigned_at = NOW()
    WHERE id = v_item_id
      AND status = 'available';

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    UPDATE public.unique_delivery_fulfillments
    SET item_id = v_item_id,
        status = 'assigned',
        assigned_at = NOW()
    WHERE id = v_fulfillment_id
      AND status = 'stock_unavailable';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'unique delivery fulfillment changed during allocation';
    END IF;

    RETURN v_item_id;
END;
$$;

REVOKE ALL ON FUNCTION public.assign_unique_delivery_for_product(UUID, UUID)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.assign_unique_delivery_for_product(UUID, UUID)
    TO service_role;

CREATE OR REPLACE FUNCTION public.goupay_assign_unique_deliveries_on_paid()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_additional_product_id UUID;
BEGIN
    IF NEW.status = 'paid'
       AND (
           TG_OP = 'INSERT'
           OR OLD.status IS DISTINCT FROM NEW.status
       ) THEN
        IF NEW.product_id IS NOT NULL THEN
            PERFORM public.assign_unique_delivery_for_product(NEW.id, NEW.product_id);
        END IF;

        IF to_regclass('public.order_bump_items') IS NOT NULL THEN
            FOR v_additional_product_id IN
                SELECT DISTINCT bump_product_id
                FROM public.order_bump_items
                WHERE order_id = NEW.id
                  AND bump_product_id IS NOT NULL
            LOOP
                PERFORM public.assign_unique_delivery_for_product(
                    NEW.id,
                    v_additional_product_id
                );
            END LOOP;
        END IF;

        FOR v_additional_product_id IN
            SELECT product_id
            FROM public.unique_delivery_order_products
            WHERE order_id = NEW.id
        LOOP
            PERFORM public.assign_unique_delivery_for_product(
                NEW.id,
                v_additional_product_id
            );
        END LOOP;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS assign_unique_deliveries_on_paid ON public.orders;
CREATE TRIGGER assign_unique_deliveries_on_paid
AFTER INSERT OR UPDATE OF status ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.goupay_assign_unique_deliveries_on_paid();

CREATE OR REPLACE FUNCTION public.goupay_assign_unique_delivery_on_bump_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_status TEXT;
BEGIN
    IF NEW.bump_product_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT status INTO v_status
    FROM public.orders
    WHERE id = NEW.order_id;

    IF v_status = 'paid' THEN
        PERFORM public.assign_unique_delivery_for_product(
            NEW.order_id,
            NEW.bump_product_id
        );
    END IF;

    RETURN NEW;
END;
$$;

DO $$
BEGIN
    IF to_regclass('public.order_bump_items') IS NOT NULL THEN
        EXECUTE 'DROP TRIGGER IF EXISTS assign_unique_delivery_on_bump_insert
            ON public.order_bump_items';
        EXECUTE 'CREATE TRIGGER assign_unique_delivery_on_bump_insert
            AFTER INSERT ON public.order_bump_items
            FOR EACH ROW
            EXECUTE FUNCTION public.goupay_assign_unique_delivery_on_bump_insert()';
    END IF;
END;
$$;

