CREATE TRIGGER backfill_waiting_unique_delivery
AFTER INSERT ON public.unique_delivery_items
FOR EACH ROW EXECUTE FUNCTION public.goupay_backfill_waiting_unique_delivery();

CREATE OR REPLACE FUNCTION public.record_unique_delivery_views(
    p_fulfillment_ids UUID[]
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    UPDATE public.unique_delivery_fulfillments
    SET first_viewed_at = COALESCE(first_viewed_at, NOW()),
        last_viewed_at = NOW(),
        view_count = view_count + 1
    WHERE id = ANY(COALESCE(p_fulfillment_ids, ARRAY[]::UUID[]))
      AND status = 'assigned';
END;
$$;

